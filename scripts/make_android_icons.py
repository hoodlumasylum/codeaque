#!/usr/bin/env python3
"""0.10.30: CodeAque Android launcher icons, made from docs/branding/codeaque-logo.png.

The whole CodeAque wordmark sits inside the 66dp safe zone of the 108dp adaptive-icon canvas, so a circle,
squircle or rounded-square mask never cuts it (0.10.29 used one square PNG that launchers zoomed into "DEAC").
Writes: adaptive foreground + monochrome layers (drawable-nodpi), legacy padded PNGs (mipmap-mdpi..xxxhdpi),
the TV banner (drawable-xhdpi/banner.png), and the same set with a small badge for the CodeAque Adult and
CodeAque Settings entries (original art: a person and a gear on a gold disc).
Run: python3 scripts/make_android_icons.py [preview.png]
"""
import math, os, sys
from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "android/app/src/main/res")
BG = (18, 20, 24, 255)          # same dark as the old icon / logo background (#121418)
GOLD = (245, 192, 64, 255)
DARK = (18, 20, 24, 255)
CANVAS = 432                    # 108dp at xxxhdpi
DENS = {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}


def logo():
    im = Image.open(os.path.join(ROOT, "docs/branding/codeaque-logo.png")).convert("RGBA")
    return im.crop(im.getbbox())


def white(im):
    """Pure white copy keeping only the alpha (monochrome layer / safe on any background)."""
    w = Image.new("RGBA", im.size, (255, 255, 255, 255)); w.putalpha(im.getchannel("A")); return w


def paste_logo(dst, L, width, cx, cy):
    h = round(L.height * width / L.width)
    s = L.resize((round(width), h), Image.LANCZOS)
    dst.alpha_composite(s, (round(cx - s.width / 2), round(cy - h / 2)))


def badge(kind, d, fg=DARK, ring=GOLD):
    """A gold disc with a person (adult) or a gear (settings), drawn 4x and scaled down."""
    S = d * 4
    b = Image.new("RGBA", (S, S), (0, 0, 0, 0)); g = ImageDraw.Draw(b)
    g.ellipse((0, 0, S - 1, S - 1), fill=ring)
    g.ellipse((S * 0.06, S * 0.06, S * 0.94, S * 0.94), outline=fg, width=max(2, int(S * 0.04)))
    c = S / 2
    if kind == "adult":
        r = S * 0.13
        g.ellipse((c - r, S * 0.24, c + r, S * 0.24 + 2 * r), fill=fg)                    # head
        g.chord((c - S * 0.25, S * 0.53, c + S * 0.25, S * 1.03), 180, 360, fill=fg)      # shoulders
        g.rectangle((c - S * 0.25, S * 0.78, c + S * 0.25, S * 0.80), fill=ring)
    else:
        ro, ri, teeth = S * 0.30, S * 0.22, 8
        pts = []
        for i in range(teeth * 4):
            a = 2 * math.pi * i / (teeth * 4)
            rr = ro if (i % 4) in (1, 2) else ri
            pts.append((c + rr * math.cos(a), c + rr * math.sin(a)))
        g.polygon(pts, fill=fg)
        h = S * 0.09
        g.ellipse((c - h, c - h, c + h, c + h), fill=ring)
    return b.resize((d, d), Image.LANCZOS)


def foreground(kind, C=CANVAS, mono=False):
    """Adaptive foreground, transparent. Everything stays inside the 66dp circle (radius C*33/108)."""
    u = C / 108.0
    im = Image.new("RGBA", (C, C), (0, 0, 0, 0)); L = logo()
    if kind is None:
        paste_logo(im, L, 68 * u, C / 2, C / 2)
    else:
        paste_logo(im, L, 62 * u, C / 2, 47 * u)
        bd = round(20 * u)
        bdg = badge(kind, bd, fg=(0, 0, 0, 0) if mono else DARK, ring=(255, 255, 255, 255) if mono else GOLD)
        im.alpha_composite(bdg, (round(C / 2 - bd / 2), round(72 * u - bd / 2)))
    return white(im) if mono else im


def legacy(kind, px, round_shape):
    """Pre-Android 8 icon: dark tile with padding and the whole logo."""
    S = px * 4
    im = Image.new("RGBA", (S, S), (0, 0, 0, 0)); g = ImageDraw.Draw(im)
    pad = S * 2 / 48
    if round_shape: g.ellipse((pad, pad, S - pad, S - pad), fill=BG)
    else: g.rounded_rectangle((pad, pad, S - pad, S - pad), radius=S * 8 / 48, fill=BG)
    L = logo()
    w = S * (34 if round_shape else 38) / 48
    if kind is None:
        paste_logo(im, L, w, S / 2, S / 2)
    else:
        paste_logo(im, L, w * 0.92, S / 2, S * 0.43)
        bd = round(S * 0.27)
        im.alpha_composite(badge(kind, bd), (round(S / 2 - bd / 2), round(S * 0.70 - bd / 2)))
    return im.resize((px, px), Image.LANCZOS)


ADAPTIVE = """<?xml version="1.0" encoding="utf-8"?>
<!-- 0.10.30: generated by scripts/make_android_icons.py. The whole logo is inside the 66dp safe zone. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/{fg}" />
    <monochrome android:drawable="@drawable/{mono}" />
</adaptive-icon>
"""


def write():
    names = {None: "ic_launcher", "adult": "ic_launcher_adult", "settings": "ic_launcher_settings"}
    nodpi = os.path.join(RES, "drawable-nodpi"); os.makedirs(nodpi, exist_ok=True)
    any26 = os.path.join(RES, "mipmap-anydpi-v26"); os.makedirs(any26, exist_ok=True)
    for kind, n in names.items():
        foreground(kind).save(os.path.join(nodpi, n + "_foreground.png"), optimize=True)
        foreground(kind, mono=True).save(os.path.join(nodpi, n + "_monochrome.png"), optimize=True)
        for suffix in ("", "_round"):
            with open(os.path.join(any26, n + suffix + ".xml"), "w") as f:
                f.write(ADAPTIVE.format(fg=n + "_foreground", mono=n + "_monochrome"))
        for d, k in DENS.items():
            out = os.path.join(RES, "mipmap-" + d); os.makedirs(out, exist_ok=True)
            legacy(kind, round(48 * k), False).save(os.path.join(out, n + ".png"), optimize=True)
            legacy(kind, round(48 * k), True).save(os.path.join(out, n + "_round.png"), optimize=True)
    vals = os.path.join(RES, "values"); os.makedirs(vals, exist_ok=True)
    with open(os.path.join(vals, "ic_launcher_colors.xml"), "w") as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
                '    <color name="ic_launcher_background">#121418</color>\n</resources>\n')
    ban = Image.new("RGBA", (320, 180), BG)              # TV banner, 160x90dp at xhdpi, logo fully inside
    paste_logo(ban, logo(), 272, 160, 90)
    os.makedirs(os.path.join(RES, "drawable-xhdpi"), exist_ok=True)
    ban.convert("RGB").save(os.path.join(RES, "drawable-xhdpi/banner.png"), optimize=True)


def squircle(C, n=5.0):
    m = Image.new("L", (C, C), 0); px = m.load(); r = C / 2
    for y in range(C):
        for x in range(C):
            if abs((x + .5 - r) / r) ** n + abs((y + .5 - r) / r) ** n <= 1: px[x, y] = 255
    return m


def preview(path):
    """Each icon under circle, squircle, rounded-square and teardrop masks (72dp of the 108dp canvas, as launchers do)."""
    C = CANVAS; vis = round(C * 72 / 108); off = (C - vis) // 2
    masks = []
    m = Image.new("L", (vis, vis), 0); ImageDraw.Draw(m).ellipse((0, 0, vis - 1, vis - 1), fill=255); masks.append(("circle", m))
    masks.append(("squircle", squircle(vis)))
    m = Image.new("L", (vis, vis), 0); ImageDraw.Draw(m).rounded_rectangle((0, 0, vis - 1, vis - 1), radius=vis * 0.18, fill=255); masks.append(("rounded square", m))
    m = Image.new("L", (vis, vis), 0); g = ImageDraw.Draw(m); g.ellipse((0, 0, vis - 1, vis - 1), fill=255); g.rectangle((vis // 2, vis // 2, vis - 1, vis - 1), fill=255); masks.append(("teardrop", m))
    kinds = [(None, "CodeAque"), ("adult", "CodeAque Adult"), ("settings", "CodeAque Settings")]
    cell = vis + 40; out = Image.new("RGBA", (cell * (len(masks) + 1) + 20, cell * len(kinds) + 60), (60, 64, 72, 255))
    g = ImageDraw.Draw(out)
    for j, (nm, _) in enumerate(masks): g.text((cell * j + 30, 15), nm, fill=(255, 255, 255, 255))
    g.text((cell * len(masks) + 30, 15), "legacy (pre-8.0)", fill=(255, 255, 255, 255))
    for i, (kind, label) in enumerate(kinds):
        full = Image.new("RGBA", (C, C), BG); full.alpha_composite(foreground(kind))
        crop = full.crop((off, off, off + vis, off + vis))
        for j, (nm, m) in enumerate(masks):
            t = Image.new("RGBA", (vis, vis), (0, 0, 0, 0)); t.paste(crop, (0, 0), m)
            out.alpha_composite(t, (cell * j + 20, cell * i + 40))
        out.alpha_composite(legacy(kind, vis, False), (cell * len(masks) + 20, cell * i + 40))
        g.text((20, cell * i + 40 + vis + 4), label, fill=(255, 255, 255, 255))
    out.save(path)


if __name__ == "__main__":
    write()
    if len(sys.argv) > 1: preview(sys.argv[1])
